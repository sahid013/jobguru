// Builds supabase/content/nobel-2026.sql from scripts/content/nobel-2026.ts:
//   • one Markdown note under আন্তর্জাতিক বিষয়াবলি → চলমান ঘটনাপ্রবাহ → নোবেল পুরস্কার ২০২৬
//   • the MCQs, so the topic's Practice button works
// Usage: npm run content:nobel → paste the file into the Supabase SQL Editor.
// Re-runnable: it replaces the note with the same title and the questions it created earlier.

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { NOTE_TITLE, QUESTION_SOURCE, TOPIC, noteBody, questions } from "./content/nobel-2026";

const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
const arr = (v: string[]) => `array[${v.map(q).join(", ")}]::text[]`;

const subject = `(select id from public.subjects where slug = ${q(TOPIC.subjectSlug)})`;
const topicBySlug = (slug: string) =>
  `(select id from public.topics where subject_id = ${subject} and slug = ${q(slug)})`;
const parent = topicBySlug(TOPIC.parentSlug);
const topic = topicBySlug(TOPIC.slug);

const out: string[] = [
  "-- Generated by scripts/generate-nobel-2026.ts — do not edit by hand.",
  "begin;",
  "",
  `-- The sub-topic (created on first run, updated after)`,
  `insert into public.topics (subject_id, parent_id, slug, title, description, points, marks, sort_order)`,
  `values (${subject}, ${parent}, ${q(TOPIC.slug)}, ${q(TOPIC.title)}, ${q(TOPIC.description)}, '{}', null, 0)`,
  `on conflict (subject_id, slug) do update set parent_id = excluded.parent_id, title = excluded.title,`,
  `  description = excluded.description, sort_order = excluded.sort_order;`,
  "",
  `-- Remove what earlier runs created`,
  `delete from public.notes where topic_id = ${topic} and title = ${q(NOTE_TITLE)};`,
  `delete from public.questions where topic_id = ${topic} and source = ${q(QUESTION_SOURCE)};`,
  "",
  `-- The note`,
  `insert into public.notes (topic_id, title, body, published, sort_order)`,
  `values (${topic}, ${q(NOTE_TITLE)}, ${q(noteBody)}, true, 0);`,
  "",
  `-- The questions`,
];

for (const m of questions) {
  out.push(
    `insert into public.questions (topic_id, stem, options, correct_index, explanation, source, published)`,
    `values (${topic}, ${q(m.stem)}, ${arr(m.options)}, ${m.correct}, ${q(m.explanation)}, ${q(QUESTION_SOURCE)}, true);`,
  );
}

out.push("", "commit;", "");

const dir = join(process.cwd(), "supabase", "content");
mkdirSync(dir, { recursive: true });
const file = join(dir, "nobel-2026.sql");
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file} — 1 note, ${questions.length} questions`);
