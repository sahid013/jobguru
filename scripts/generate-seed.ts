// Generates supabase/seed.sql from src/data/syllabus.ts.
// Usage: npm run db:seed-sql   → then run the file in the Supabase SQL editor.
// Safe to re-run: rows are upserted by slug, so your notes and questions are kept.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { syllabus, type SeedTopic } from "../src/data/syllabus";

const q = (v: string | null | undefined) =>
  v == null ? "null" : `'${v.replace(/'/g, "''")}'`;
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const arr = (v: string[] | undefined) =>
  !v || v.length === 0 ? "'{}'" : `array[${v.map(q).join(", ")}]::text[]`;

const out: string[] = [
  "-- Generated by scripts/generate-seed.ts — do not edit by hand.",
  "begin;",
  "",
];

syllabus.forEach((s, i) => {
  out.push(
    `insert into public.subjects (slug, lang, title, marks, sort_order, sources, source_note)`,
    `values (${q(s.slug)}, ${q(s.lang)}, ${q(s.title)}, ${s.marks}, ${i}, ${q(JSON.stringify(s.sources ?? []))}::jsonb, ${q(s.source_note)})`,
    `on conflict (slug) do update set lang = excluded.lang, title = excluded.title, marks = excluded.marks,`,
    `  sort_order = excluded.sort_order, sources = excluded.sources, source_note = excluded.source_note;`,
    "",
  );

  const subj = `(select id from public.subjects where slug = ${q(s.slug)})`;
  const walk = (list: SeedTopic[], parentSlug: string | null) =>
    list.forEach((t, j) => {
      const parent = parentSlug
        ? `(select id from public.topics where subject_id = ${subj} and slug = ${q(parentSlug)})`
        : "null";
      out.push(
        `insert into public.topics (subject_id, parent_id, slug, title, description, points, marks, sort_order)`,
        `values (${subj}, ${parent}, ${q(t.slug)}, ${q(t.title)}, ${q(t.description)}, ${arr(t.points)}, ${n(t.marks)}, ${j})`,
        `on conflict (subject_id, slug) do update set parent_id = excluded.parent_id, title = excluded.title,`,
        `  description = excluded.description, points = excluded.points, marks = excluded.marks, sort_order = excluded.sort_order;`,
        "",
      );
      walk(t.children ?? [], t.slug);
    });
  walk(s.topics, null);
});

out.push("commit;", "");

const file = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file}`);
